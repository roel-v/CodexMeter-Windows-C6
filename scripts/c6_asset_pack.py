"""Pack immutable theme artwork for direct, read-only ESP32-C6 flash mapping."""
from pathlib import Path
import json
import struct
import zlib

PARTITION_OFFSET = 0x610000
PARTITION_SIZE = 0x960000
MAGIC = b"CMASSET1"


def build_pack(source: Path, output: Path) -> dict:
    output.mkdir(parents=True, exist_ok=True)
    blob = bytearray(32)
    entries = []
    for path in sorted(source.iterdir()):
        if path.suffix not in {".rgb565", ".argb8888", ".bin"}:
            continue
        data = path.read_bytes()
        if not data:
            raise ValueError(f"Empty asset: {path}")
        blob.extend(b"\xff" * (-len(blob) % 16))
        entries.append({"name": path.name, "offset": len(blob), "size": len(data),
                        "crc32": zlib.crc32(data)})
        blob.extend(data)
    if not entries or len(blob) > PARTITION_SIZE:
        raise ValueError("C6 asset pack is empty or exceeds its flash partition")
    crc = zlib.crc32(blob[32:])
    struct.pack_into("<8sIII", blob, 0, MAGIC, len(blob), crc, len(entries))
    header = ["// Generated by scripts/c6_asset_pack.py; do not edit.",
              "#pragma once", "#include <stdint.h>",
              "struct C6AssetEntry { const char* name; uint32_t offset, size, crc; };",
              f"constexpr uint32_t C6_ASSET_BYTES = {len(blob)};",
              f"constexpr uint32_t C6_ASSET_CRC = {crc}U;",
              "static const C6AssetEntry C6_ASSETS[] = {"]
    for entry in entries:
        header.append(f'  {{"{entry["name"]}", {entry["offset"]}, {entry["size"]}, {entry["crc32"]}U}},')
    header.append("};\n")
    outputs = {"c6_assets.bin": bytes(blob),
               "c6_asset_index.h": "\n".join(header).encode()}
    for name, content in outputs.items():
        path = output / name
        if not path.exists() or path.read_bytes() != content:
            path.write_bytes(content)
    manifest = {"offset": PARTITION_OFFSET, "bytes": len(blob), "crc32": crc, "files": entries}
    (output / "c6_assets.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return manifest
